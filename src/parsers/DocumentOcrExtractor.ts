export interface ExtractedDocumentData {
  vehicleRegistrationNumber?: string;
  ewayBillNumber?: string;
  biltyNumber?: string;
  grossWeightKg?: number;
  tareWeightKg?: number;
  netWeightKg?: number;
  extractedDates: Date[];
  permitNumber?: string;
  fitnessCertificateNumber?: string;
  rawText: string;
}

export class DocumentOcrExtractor {
  // 1. Indian Vehicle Registration Number Pattern (e.g., MH 40 AK 1234, MH31AP9999, DL 1C AA 1234)
  private static readonly REGEX_VEHICLE_NO =
    /\b([A-Z]{2}[ -]?[0-9]{1,2}[ -]?[A-Z]{1,3}[ -]?[0-9]{4})\b/i;

  // 2. e-Way Bill 12-digit number pattern
  private static readonly REGEX_EWAY_BILL = /\b([0-9]{12})\b/;

  // 3. Bilty / LR (Lorry Receipt) / Consignment Note pattern
  private static readonly REGEX_BILTY_NO =
    /\b(?:Bilty|Consignment\s*Note|Receipt|GR|LR)(?:\s*(?:No|Number|#|\/|Bilty))*[:\s\-]+([A-Z0-9\/-]{3,25})/i;

  // 4. Dharam Kanta Weighbridge Slips (Gross, Tare, Net weights in MT or KG)
  private static readonly REGEX_GROSS_WT =
    /(?:Gross|G\.W\.|GVW)(?:\s*(?:WT|WEIGHT|LOAD))?[\s:.]*([0-9]{1,6}(?:\.[0-9]+)?)\s*(MT|T|Ton|Kg)?/i;
  private static readonly REGEX_TARE_WT =
    /(?:Tare|T\.W\.|Unladen)(?:\s*(?:WT|WEIGHT|LOAD))?[\s:.]*([0-9]{1,6}(?:\.[0-9]+)?)\s*(MT|T|Ton|Kg)?/i;
  private static readonly REGEX_NET_WT =
    /(?:Net|N\.W\.|Payload)(?:\s*(?:WT|WEIGHT|LOAD))?[\s:.]*([0-9]{1,6}(?:\.[0-9]+)?)\s*(MT|T|Ton|Kg)?/i;

  // 5. Permit & Fitness Patterns
  private static readonly REGEX_PERMIT_NO =
    /(?:Permit|AIP)[\s#.:-]*([A-Z0-9\/-]{5,25})/i;
  private static readonly REGEX_FITNESS_NO =
    /(?:Fitness|Form 38)[\s#.:-]*([A-Z0-9\/-]{5,25})/i;

  // 6. Indian Date Patterns (DD/MM/YYYY or DD-MM-YYYY)
  private static readonly REGEX_DATES =
    /\b([0-3]?[0-9])[-\/.]([0-1]?[0-9])[-\/.](20[0-9]{2}|19[0-9]{2})\b/g;

  /**
   * Extracts structured freight metadata from raw OCR text generated by Tesseract.
   */
  public static extractMetadata(rawOcrText: string): ExtractedDocumentData {
    if (!rawOcrText) {
      return { extractedDates: [], rawText: '' };
    }

    const cleanText = rawOcrText.replace(/\r?\n|\r/g, ' ');

    // Match Vehicle Reg No
    let vehicleRegistrationNumber: string | undefined;
    const vehicleMatch = cleanText.match(this.REGEX_VEHICLE_NO);
    if (vehicleMatch) {
      vehicleRegistrationNumber = vehicleMatch[1].replace(/[\s-]/g, '').toUpperCase();
    }

    // Match e-Way Bill
    let ewayBillNumber: string | undefined;
    const ewayMatch = cleanText.match(this.REGEX_EWAY_BILL);
    if (ewayMatch) {
      ewayBillNumber = ewayMatch[1];
    }

    // Match Bilty
    let biltyNumber: string | undefined;
    const biltyMatch = cleanText.match(this.REGEX_BILTY_NO);
    if (biltyMatch) {
      biltyNumber = biltyMatch[1].trim();
    }

    // Match Weighbridge Weights (Normalize to Kilograms)
    const grossWeightKg = this.parseWeightInKg(cleanText, this.REGEX_GROSS_WT);
    const tareWeightKg = this.parseWeightInKg(cleanText, this.REGEX_TARE_WT);
    const netWeightKg = this.parseWeightInKg(cleanText, this.REGEX_NET_WT);

    // Match Permit and Fitness numbers
    const permitMatch = cleanText.match(this.REGEX_PERMIT_NO);
    const permitNumber = permitMatch ? permitMatch[1].trim() : undefined;

    const fitnessMatch = cleanText.match(this.REGEX_FITNESS_NO);
    const fitnessCertificateNumber = fitnessMatch ? fitnessMatch[1].trim() : undefined;

    // Match dates
    const extractedDates: Date[] = [];
    const dateMatches = cleanText.matchAll(this.REGEX_DATES);
    for (const match of dateMatches) {
      const day = parseInt(match[1], 10);
      const month = parseInt(match[2], 10) - 1;
      const year = parseInt(match[3], 10);
      const parsedDate = new Date(Date.UTC(year, month, day));
      if (!isNaN(parsedDate.getTime())) {
        extractedDates.push(parsedDate);
      }
    }

    return {
      vehicleRegistrationNumber,
      ewayBillNumber,
      biltyNumber,
      grossWeightKg,
      tareWeightKg,
      netWeightKg,
      extractedDates,
      permitNumber,
      fitnessCertificateNumber,
      rawText: rawOcrText
    };
  }

  private static parseWeightInKg(text: string, regex: RegExp): number | undefined {
    const match = text.match(regex);
    if (!match) return undefined;

    const val = parseFloat(match[1]);
    if (isNaN(val)) return undefined;

    const unit = match[2]?.toUpperCase();
    // If unit is Ton/MT, or if val < 100, assume Metric Tonnes and convert to KG
    if (unit === 'MT' || unit === 'T' || unit === 'TON' || val <= 60) {
      return Math.round(val * 1000);
    }
    return Math.round(val);
  }
}
